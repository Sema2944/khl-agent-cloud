# src/hockey_logic.py
"""
Хоккейная «турнирная логика» (эвристика) без живой таблицы.

Задача:
- На вход: team1, team2, league (KHL/NHL/OTHER)
- На выход: структурированные заметки:
  * краткий профиль команд (верх/середина/низ),
  * сценарии (топ vs дно, топ vs топ и т.д.),
  * универсальная мысль про распределение усилий.

Важно:
- Это не прогноз и не рекомендация.
- Это контекст для интерпретации движения линии/рынка.
"""

from __future__ import annotations

from typing import Literal

LeagueName = Literal["KHL", "NHL", "OTHER"]

# Эвристика tiers для КХЛ (можно расширять)
KHL_TOP_TEAMS = {
    "СКА",
    "ЦСКА",
    "АК БАРС",
    "АВАНГАРД",
    "ДИНАМО МСК",
    "ТОРПЕДО",
    "ЛОКОМОТИВ",
}

KHL_MID_TEAMS = {
    "САЛАВАТ ЮЛАЕВ",
    "СПАРТАК",
    "СЕВЕРСТАЛЬ",
    "АВТОМОБИЛИСТ",
    "МЕТАЛЛУРГ",
    "ТРАКТОР",
    "ЙОКЕРИТ",
}

KHL_BOTTOM_TEAMS = {
    "СОЧИ",
    "АМУР",
    "КУНЬЛУНЬ",
    "НЕФТЕХИМИК",
}


def _normalize(name: str) -> str:
    return (name or "").strip().upper()


def _get_khl_tier(name: str) -> str:
    n = _normalize(name)
    if n in KHL_TOP_TEAMS:
        return "top"
    if n in KHL_BOTTOM_TEAMS:
        return "bottom"
    if n in KHL_MID_TEAMS:
        return "mid"
    return "unknown"


def _label(tier: str) -> str:
    return {
        "top": "верх таблицы / претендент",
        "mid": "середина таблицы",
        "bottom": "нижняя часть таблицы",
        "unknown": "статус не определён (без таблицы)",
    }.get(tier, "статус не определён")


def build_match_context_notes(team1: str, team2: str, league: LeagueName = "KHL") -> list[str]:
    """
    Возвращает список строк (без пустых), готовых для вставки в UI/LLM prompt.
    """
    t1 = (team1 or "").strip()
    t2 = (team2 or "").strip()
    if not t1 or not t2:
        return []

    if league != "KHL":
        return [
            "Турнирный контекст (эвристика) сейчас настроен в первую очередь для КХЛ.",
            "Для других лиг важнее смотреть: форму, календарь, состав, мотивацию и плотность таблицы.",
        ]

    tier1 = _get_khl_tier(t1)
    tier2 = _get_khl_tier(t2)

    lines: list[str] = []
    lines.append(f"{t1}: {_label(tier1)}.")
    lines.append(f"{t2}: {_label(tier2)}.")

    # Сценарии
    if {tier1, tier2} == {"top", "bottom"}:
        fav = t1 if tier1 == "top" else t2
        dog = t2 if fav == t1 else t1
        lines += [
            f"Сценарий: {fav} (топ) против {dog} (низ).",
            "Часто фаворит играет прагматично: контроль без максимального риска и темпа.",
            "Аутсайдер может держаться, если зацепит первый отрезок и вратарь «поймает» матч.",
            "Если у фаворита скоро игра с прямым конкурентом — фокус/интенсивность здесь могут быть ниже.",
        ]
    elif tier1 == "top" and tier2 == "top":
        lines += [
            "Сценарий: матч двух топ-команд — высокая ценность очков и максимальная концентрация.",
            "Старт нередко осторожный, а после первого гола динамика может резко меняться.",
        ]
    elif tier1 == "mid" and tier2 == "mid":
        lines += [
            "Сценарий: встреча двух середняков — решают форма, вратари и дисциплина.",
            "Рынок чаще ошибается именно в таких матчах: контекст важнее громких имён.",
        ]
    elif {"top", "mid"} == {tier1, tier2}:
        lines += [
            "Сценарий: фаворит есть, но середняк способен держать игру долго (особенно дома/при сильном вратаре).",
        ]
    elif tier1 == "bottom" or tier2 == "bottom":
        lines += [
            "Сценарий: участие команды из низа — многое решает мотивация и «режим без давления».",
        ]

    # Универсальная мысль (важно для твоего позиционирования “рынка”)
    lines += [
        "Ключевая мысль: топ-команды часто распределяют усилия по календарю.",
        "Это влияет на темп, риск-профиль и то, как рынок переоценивает «громкое имя».",
    ]

    # чистим пустые
    return [x.strip() for x in lines if str(x).strip()]
